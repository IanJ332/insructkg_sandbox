"""Create an explicitly synthetic, CC0 educational PDF for local integration QA.

Requires reportlab; never incorporates research PDFs or real student records.
"""

import argparse
import hashlib
import json
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--output-dir", type=Path, default=ROOT / "artifacts/original-integration")
parser.add_argument(
    "--content-exclusions",
    type=Path,
    help="Optional explicitly reviewed Docling item exclusions for this synthetic fixture",
)
args = parser.parse_args()
OUT = args.output_dir.resolve()
OUT.mkdir(parents=True, exist_ok=True)
PDF = OUT / "synthetic-sql-lesson.pdf"
if PDF.exists():
    raise SystemExit(
        "Fixture already exists; choose a fresh --output-dir to preserve historical evidence."
    )
SECTIONS = [
    (
        "Join predicates",
        "A join predicate compares column values from two tables to decide which rows match. An equality predicate can compare a foreign key with the referenced primary key. A matching row satisfies the predicate; a nonmatching row does not. Understanding a join predicate is prerequisite knowledge for interpreting inner joins and left outer joins.",
    ),
    (
        "Inner joins",
        "An inner join returns only pairs of rows that satisfy its join predicate. Interpreting an inner join depends on understanding join predicates. Rows with no matching partner do not appear in the result. Omitting the predicate instead combines every row of one table with every row of the other table, which is a Cartesian product rather than the intended match.",
    ),
    (
        "Left outer joins",
        "A left outer join retains every row of its left input. It uses the join predicate to find matching right rows. When a left row has no matching right row, right-side columns contain NULL. Interpreting a left outer join depends on understanding join predicates and NULL semantics. An inner join cannot represent all unmatched left rows.",
    ),
    (
        "NULL semantics",
        "NULL marks a missing or unknown value. An equality comparison involving NULL is unknown rather than true. Use IS NULL to identify missing values. Understanding NULL semantics is prerequisite knowledge for explaining unmatched rows in a left outer join and the behavior of COUNT on a nullable right-side column.",
    ),
    (
        "Grouped counts",
        "GROUP BY partitions rows using the grouping columns. COUNT(*) counts result rows, whereas COUNT(column) counts only rows whose column value is non-NULL. After a left outer join, COUNT(*) includes the retained unmatched row; COUNT of a right-side key can represent zero matches. Interpreting grouped counts depends on understanding grouping and NULL semantics. An aggregate condition over groups belongs in HAVING; a row condition applied before grouping belongs in WHERE.",
    ),
]
styles = getSampleStyleSheet()
styles["Title"].textColor = colors.HexColor("#14334b")
story = [
    Paragraph("Synthetic SQL lesson", styles["Title"]),
    Paragraph("SYNTHETIC COURSE MATERIAL - LOCAL RESEARCH DEMONSTRATION", styles["Heading3"]),
    Paragraph(
        "Created solely for integration validation. No professor material or student data. This original fixture is dedicated to the public domain under CC0 1.0.",
        styles["BodyText"],
    ),
    Spacer(1, 12),
]
for title, text in SECTIONS:
    story.extend(
        [Paragraph(title, styles["Heading2"]), Paragraph(text, styles["BodyText"]), Spacer(1, 8)]
    )


def footer(canvas, document):
    canvas.setFont("Helvetica", 8)
    canvas.drawString(0.65 * inch, 0.4 * inch, "Synthetic integration fixture | CC0 1.0")
    canvas.drawRightString(7.85 * inch, 0.4 * inch, str(document.page))


SimpleDocTemplate(
    str(PDF),
    rightMargin=0.65 * inch,
    leftMargin=0.65 * inch,
    topMargin=0.55 * inch,
    bottomMargin=0.65 * inch,
    title="Synthetic SQL lesson",
    author="SIIP synthetic integration validation",
).build(story, onFirstPage=footer, onLaterPages=footer)
digest = hashlib.sha256(PDF.read_bytes()).hexdigest()
(OUT / "synthetic_pdf_manifest.json").write_text(
    json.dumps(
        {
            digest: {
                "provenance": "Explicitly synthetic educational fixture generated by scripts/create_original_integration_fixture.py; no private source content.",
                "license": "CC0-1.0",
                "content_exclusions": json.loads(
                    args.content_exclusions.read_text(encoding="utf-8")
                )
                if args.content_exclusions
                else [],
            }
        },
        indent=2,
    ),
    encoding="utf-8",
)
(OUT / "fixture_source.json").write_text(
    json.dumps({"path": str(PDF), "sha256": digest, "sections": SECTIONS}, indent=2),
    encoding="utf-8",
)
print(json.dumps({"pdf": str(PDF), "sha256": digest}))
